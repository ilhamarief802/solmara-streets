const BY_ID = new Map(DISTRICTS.map((district) => [district.id, district]));

export function districtById(id) {
  return BY_ID.get(id) ?? BY_ID.get('downtown');
}

export function districtIds() {
  return DISTRICTS.map((district) => district.id);
}

/** A short human summary used by the debug overlay and the report. */
export function describeDistricts() {
  return DISTRICTS.map((district) => `${district.name} (${district.id})`).join(', ');
}
